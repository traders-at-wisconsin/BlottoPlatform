"""Generates the frontend's Firestore types from functions/schema.py.

    functions/venv/bin/python scripts/gen_types.py          # write schema/
    functions/venv/bin/python scripts/gen_types.py --check  # fail if schema/ is stale (CI)

Writes schema/firestore.schema.json (JSON Schema of every document model) and
schema/firestore.ts (TypeScript interfaces built from that JSON Schema).
Timestamps become Firestore `Timestamp`, which is what the JS SDK returns.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "functions"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from schema import DOCUMENT_MODELS  # noqa: E402

OUT = ROOT / "schema"
HEADER = """\
// Generated by scripts/gen_types.py from functions/schema.py. Do not edit.
import type { Timestamp } from "firebase/firestore";
"""


def json_schema():
    _, schema = models_json_schema([(m, "validation") for m in DOCUMENT_MODELS], by_alias=True)
    return schema


def ts_type(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "anyOf" in s:
        return " | ".join(ts_type(x) for x in s["anyOf"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    t = s.get("type")
    if t == "string":
        return "Timestamp" if s.get("format") == "date-time" else "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    return "unknown"


def typescript(schema):
    out = [HEADER]
    for name, d in sorted(schema["$defs"].items()):
        if "enum" in d:
            out.append(f"export type {name} = {ts_type(d)};\n")
            continue
        lines = [f"export interface {name} {{"]
        for field, fs in d.get("properties", {}).items():
            # Fields with a default are always written, so they are never optional when read.
            lines.append(f"  {field}: {ts_type(fs)};")
        lines.append("}\n")
        out.append("\n".join(lines))
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated files are stale")
    args = parser.parse_args()

    schema = json_schema()
    files = {
        OUT / "firestore.schema.json": json.dumps(schema, indent=2, sort_keys=True) + "\n",
        OUT / "firestore.ts": typescript(schema),
    }
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale:
            print("Stale generated types; run scripts/gen_types.py:", *map(str, stale), sep="\n  ")
            sys.exit(1)
        return
    OUT.mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
    print("wrote", *(p.relative_to(ROOT) for p in files))


if __name__ == "__main__":
    main()
